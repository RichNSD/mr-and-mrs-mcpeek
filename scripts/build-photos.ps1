<#
  Turns the full-size exports into the three web-ready sizes the site uses,
  and writes js/photos.js so the gallery knows each photo's shape.

    photos/thumb/NNN.jpg  800px long edge   gallery grid
    photos/web/NNN.jpg    2000px long edge  full-screen viewer
    photos/full/NNN.jpg   4000px long edge  "Save this photo" download (print quality)

  Re-encoding also strips all metadata, including the GPS location of the house.

  Usage:  pwsh scripts/build-photos.ps1 [-Source path/to/exports] [-Force]
#>
param(
  [string]$Source = (Join-Path $PSScriptRoot '..' 'exports'),
  [switch]$Force
)

$ErrorActionPreference = 'Stop'
$root = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
$sizes = @(
  @{ Name = 'thumb'; LongEdge = 800;  Quality = 80 }
  @{ Name = 'web';   LongEdge = 2000; Quality = 82 }
  @{ Name = 'full';  LongEdge = 4000; Quality = 90 }
)
foreach ($s in $sizes) { New-Item -ItemType Directory -Force (Join-Path $root 'photos' $s.Name) | Out-Null }

$files = Get-ChildItem $Source -Filter *.jpg | Sort-Object Name
if (-not $files) { throw "No .jpg files found in $Source" }
Write-Host "Processing $($files.Count) photos from $Source"

$photos = $files | ForEach-Object -ThrottleLimit 6 -Parallel {
  Add-Type -AssemblyName System.Drawing
  $file = $_; $root = $using:root; $sizes = $using:sizes; $force = $using:Force
  $id = [regex]::Match($file.BaseName, '(\d+)$').Groups[1].Value.PadLeft(3, '0')
  $codec = [System.Drawing.Imaging.ImageCodecInfo]::GetImageEncoders() | Where-Object MimeType -eq 'image/jpeg'

  $stream = [System.IO.File]::OpenRead($file.FullName)
  $img = [System.Drawing.Image]::FromStream($stream, $false, $false)
  try {
    # Apply the camera's rotation flag, since the metadata is about to be dropped
    if ($img.PropertyIdList -contains 274) {
      switch ($img.GetPropertyItem(274).Value[0]) {
        3 { $img.RotateFlip('Rotate180FlipNone') }
        6 { $img.RotateFlip('Rotate90FlipNone') }
        8 { $img.RotateFlip('Rotate270FlipNone') }
      }
    }

    $dims = $null
    foreach ($s in $sizes) {
      $scale = [math]::Min(1.0, $s.LongEdge / [math]::Max($img.Width, $img.Height))
      $w = [int][math]::Round($img.Width * $scale)
      $h = [int][math]::Round($img.Height * $scale)
      if ($s.Name -eq 'full') { $dims = @{ w = $w; h = $h } }

      $out = Join-Path $root 'photos' $s.Name "$id.jpg"
      if (-not $force -and (Test-Path $out) -and (Get-Item $out).LastWriteTime -gt $file.LastWriteTime) { continue }

      $bmp = [System.Drawing.Bitmap]::new($w, $h)
      $g = [System.Drawing.Graphics]::FromImage($bmp)
      $g.InterpolationMode = 'HighQualityBicubic'
      $g.PixelOffsetMode = 'HighQuality'
      $g.CompositingQuality = 'HighQuality'
      $attr = [System.Drawing.Imaging.ImageAttributes]::new()
      $attr.SetWrapMode('TileFlipXY')  # avoids a faint dark fringe on the edges
      $g.DrawImage($img, [System.Drawing.Rectangle]::new(0, 0, $w, $h), 0, 0, $img.Width, $img.Height, 'Pixel', $attr)

      $params = [System.Drawing.Imaging.EncoderParameters]::new(1)
      $params.Param[0] = [System.Drawing.Imaging.EncoderParameter]::new([System.Drawing.Imaging.Encoder]::Quality, [long]$s.Quality)
      $bmp.Save($out, $codec, $params)
      $g.Dispose(); $bmp.Dispose(); $attr.Dispose()
    }
    [pscustomobject]@{ id = $id; w = $dims.w; h = $dims.h }
  }
  finally {
    $img.Dispose(); $stream.Dispose()
  }
}

$lines = $photos | Sort-Object id | ForEach-Object { "  { id: `"$($_.id)`", w: $($_.w), h: $($_.h) }," }
$js = @(
  '// Generated by scripts/build-photos.ps1. Do not edit by hand.'
  'window.PHOTOS = ['
  $lines
  '];'
  ''
) -join "`n"
[System.IO.File]::WriteAllText((Join-Path $root 'js' 'photos.js'), $js)

foreach ($s in $sizes) {
  $mb = (Get-ChildItem (Join-Path $root 'photos' $s.Name) -Filter *.jpg | Measure-Object Length -Sum).Sum / 1MB
  Write-Host ("{0,-6} {1,7:N1} MB" -f $s.Name, $mb)
}
Write-Host "Wrote js/photos.js with $($photos.Count) photos"
